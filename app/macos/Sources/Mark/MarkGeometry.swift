    /// The mark's outline, for asking whether a point lies on it (within
    /// 2 design px of a segment). Bucketed on a coarse grid, so the build
    /// stays cheap in an unoptimised app.
    struct Outline {
        let points: [SIMD2<Float>]
        private var cells: [Int: [Int]] = [:]
        private static let cell: Float = 16

        init(_ pts: [SIMD2<Float>]) {
            points = pts
            for i in pts.indices {
                let a = pts[i], b = pts[(i + 1) % pts.count]
                for k in Self.keys(near: (a + b) / 2, radius: simd_length(b - a) / 2 + 2) {
                    cells[k, default: []].append(i)
                }
            }
        }

        private static func keys(near p: SIMD2<Float>, radius r: Float) -> [Int] {
            let x0 = Int(((p.x - r) / cell).rounded(.down)), x1 = Int(((p.x + r) / cell).rounded(.down))
            let y0 = Int(((p.y - r) / cell).rounded(.down)), y1 = Int(((p.y + r) / cell).rounded(.down))
            var out = [Int]()
            for y in y0...y1 { for x in x0...x1 { out.append(y * 4096 + x) } }
            return out
        }

        func contains(_ p: SIMD2<Float>) -> Bool {
            let k = Int((p.y / Self.cell).rounded(.down)) * 4096 + Int((p.x / Self.cell).rounded(.down))
            for i in cells[k] ?? [] {
                let a = points[i], b = points[(i + 1) % points.count]
                let ab = b - a
                let t = min(max(simd_dot(p - a, ab) / max(simd_length_squared(ab), 1e-6), 0), 1)
                if simd_length(p - (a + ab * t)) < 2 { return true }
            }
            return false
        }
    }

    /// The backplate's colour: the ribbon's dark inner red (linear).
    static let backplate = SIMD3<Float>(pow(150 / 255, 2.2), pow(22 / 255, 2.2),
                                        pow(52 / 255, 2.2))

    /// Ear-clipping triangulation of a simple polygon (the silhouette).
    static func triangulate(_ poly: [SIMD2<Float>]) -> [Int] {
        var ids = Array(poly.indices)
        func cross(_ o: SIMD2<Float>, _ a: SIMD2<Float>, _ b: SIMD2<Float>) -> Float {
            (a.x - o.x) * (b.y - o.y) - (a.y - o.y) * (b.x - o.x)
        }
        // Orientation: the sign of the polygon's area.
        var area: Float = 0
        for i in poly.indices {
            let a = poly[i], b = poly[(i + 1) % poly.count]
            area += a.x * b.y - b.x * a.y
        }
        let sign: Float = area > 0 ? 1 : -1
        var out = [Int]()
        var guardCount = 0
        while ids.count > 3 && guardCount < 100_000 {
            guardCount += 1
            var clipped = false
            for k in ids.indices {
                let i0 = ids[(k + ids.count - 1) % ids.count], i1 = ids[k]
                let i2 = ids[(k + 1) % ids.count]
                let a = poly[i0], b = poly[i1], c = poly[i2]
                if cross(a, b, c) * sign <= 0 { continue }        // reflex
                var inside = false
                for j in ids where j != i0 && j != i1 && j != i2 {
                    let p = poly[j]
                    if cross(a, b, p) * sign >= 0 && cross(b, c, p) * sign >= 0
                        && cross(c, a, p) * sign >= 0 { inside = true; break }
                }
                if inside { continue }
                out += [i0, i1, i2]
                ids.remove(at: k)
                clipped = true
                break
            }
            if !clipped { break }      // degenerate: stop rather than loop
        }
        if ids.count == 3 { out += ids }
        return out
    }

    /// Smoothstep on 0...1.
    static func smooth(_ x: Float) -> Float {
        let c = min(max(x, 0), 1)
        return c * c * (3 - 2 * c)
    }

    // ---- tessellation ---------------------------------------------------------

    struct Vertex {
        var position: SIMD4<Float>   // x, y (design px), 0, 0
        var color: SIMD4<Float>      // linear rgb, 1
        var edge: SIMD4<Float>       // px to edge A, px to edge B, rim A, rim B
        var extra: SIMD4<Float>      // film, t, v, 0
        var sheen: SIMD4<Float>      // across direction xy, curve, facing
        var glow: SIMD4<Float>       // glow reach from edge A, from edge B
    }

    static let along = 480
    static let across = 16

    /// The mesh: vertex and index buffers, the index count, and how many
    /// of those indices (the first ones) are the silhouette backplate --
    /// drawn alone for the flat mark of the tiniest icon.
    static func build(device: MTLDevice) -> (MTLBuffer, MTLBuffer, Int, Int)? {
        var verts = [Vertex]()
        var idx = [UInt32]()
        // First, a backplate: the whole silhouette, filled in the dark
        // inner red, so that wherever two sheets meet no hairline crack
        // can show the background. Holes are cut from it like the strip.
        let outline = Outline(MarkTrace.silhouette)
        let plate = SIMD4<Float>(backplate, 1)
        for p in outline.points {
            verts.append(Vertex(position: [p.x, p.y, 0, 0], color: plate,
                                edge: [1e4, 1e4, 0, 0], extra: [1, 0, 0.5, 0],
                                sheen: [1, 0, 0, 0.5], glow: [0, 0, 0, 0]))
        }
        idx += triangulate(outline.points).map { UInt32($0) }
        let plateCount = idx.count
        for layer in layers {
            // Densest at the sheet's ends, where it meets other sheets.
            let ts = (0..<along).map { i -> Float in
                let u = Float(i) / Float(along - 1)
                return 0.35 * u + 0.65 * (0.5 - 0.5 * cos(.pi * u))
            }
            var a = resample(layer.a, at: ts)
            var b = resample(layer.b, at: ts)
            if layer.capEnd > 0 { taperEnd(&a, &b, ts: ts, fraction: layer.capEnd) }
            let base = UInt32(verts.count)
            for i in 0..<along {
                let t = ts[i]
                let chord = simd_length(b[i] - a[i])
                let dir = chord > 1e-3 ? (b[i] - a[i]) / chord
                    : simd_normalize(b[max(i - 1, 0)] - a[max(i - 1, 0)] + [1e-3, 0])
                // One rule for every edge: where it lies on the outline it
                // is the outline (a hairline and the warm outline glow, the
                // same weight everywhere); inside, a hairline at most.
                let rimA = outline.contains(a[i]) ? max(layer.rimA, 1.3)
                                                  : min(layer.rimA, 1.0)
                let rimB = outline.contains(b[i]) ? max(layer.rimB, 1.3)
                                                  : min(layer.rimB, 1.0)
                for j in 0..<across {
                    let v = Float(j) / Float(across - 1)
                    let p = a[i] + (b[i] - a[i]) * v
                    verts.append(Vertex(
                        position: [p.x, p.y, 0, 0],
                        color: SIMD4(color(layer, t, v), 1),
                        edge: [v * chord, (1 - v) * chord, rimA, rimB],
                        extra: [layer.film ? 1 : 0, t, v, 0],
                        sheen: [dir.x, dir.y, layer.curve, layer.facing],
                        glow: [layer.glowA(t), layer.glowB(t), layer.glowHueA(t), 0]))
                }
            }
            for i in 0..<(along - 1) {
                for j in 0..<(across - 1) {
                    let p = base + UInt32(i * across + j)
                    let q = p + UInt32(across)
                    idx += [p, q, p + 1, p + 1, q, q + 1]
                }
            }
        }
        guard let vb = device.makeBuffer(
                  bytes: verts, length: verts.count * MemoryLayout<Vertex>.stride),
              let ib = device.makeBuffer(
                  bytes: idx, length: idx.count * MemoryLayout<UInt32>.stride)
        else { return nil }
        return (vb, ib, idx.count, plateCount)
    }

    /// Bilinear in the layer's table (t rows, v at 0 / 0.5 / 1), sRGB in,
    /// linear out.
    static func color(_ l: Layer, _ t: Float, _ v: Float) -> SIMD3<Float> {
        var r = 0
        while r + 1 < l.t.count - 1 && t > l.t[r + 1] { r += 1 }
        let ft = min(max((t - l.t[r]) / max(l.t[r + 1] - l.t[r], 1e-4), 0), 1)
        func row(_ k: Int) -> SIMD3<Float> {
            let c = l.colors[k]
            let x = v * Float(c.count - 1)
            let j = min(Int(x), c.count - 2)
            return c[j] + (c[j + 1] - c[j]) * (x - Float(j))
        }
        let s = row(r) + (row(r + 1) - row(r)) * ft
        return SIMD3(pow(s.x / 255, 2.2), pow(s.y / 255, 2.2), pow(s.z / 255, 2.2))
    }

    /// Catmull-Rom through `pts`, then `n` points evenly spaced by arc
    /// length.
    static func resample(_ pts: [SIMD2<Float>], _ n: Int) -> [SIMD2<Float>] {
        resample(pts, at: (0..<n).map { Float($0) / Float(n - 1) })
    }

    /// Catmull-Rom through `pts`, then points at the given arc-length
    /// fractions (ascending, 0...1).
    static func resample(_ pts: [SIMD2<Float>], at fractions: [Float]) -> [SIMD2<Float>] {
        var dense = [SIMD2<Float>]()
        let k = pts.count
        for i in 0..<(k - 1) {
            let p0 = pts[max(i - 1, 0)], p1 = pts[i]
            let p2 = pts[i + 1], p3 = pts[min(i + 2, k - 1)]
            // Each term in steps, its scalars typed: integer literals
            // among SIMD2's operators sent an older Swift's type checker
            // past its time limit on this step.
            let two: Float = 2, three: Float = 3
            let four: Float = 4, five: Float = 5, half: Float = 0.5
            let a: SIMD2<Float> = two * p1
            let bPart: SIMD2<Float> = p2 - p0
            var cPart: SIMD2<Float> = two * p0 - five * p1
            cPart += four * p2 - p3
            var dPart: SIMD2<Float> = three * p1 - p0
            dPart += p3 - three * p2
            for s in 0..<32 {
                let f = Float(s) / 32
                let f2 = f * f
                let f3 = f2 * f
                var sum: SIMD2<Float> = a + bPart * f
                sum += cPart * f2
                sum += dPart * f3
                dense.append(sum * half)
            }
        }
        dense.append(pts[k - 1])
        var acc = [Float](repeating: 0, count: dense.count)
        for i in 1..<dense.count {
            acc[i] = acc[i - 1] + simd_length(dense[i] - dense[i - 1])
        }
        let total = acc.last ?? 1
        var out = [SIMD2<Float>]()
        var j = 0
        for f in fractions {
            let target = total * f
            while j + 1 < dense.count - 1 && acc[j + 1] < target { j += 1 }
            let seg = max(acc[j + 1] - acc[j], 1e-4)
            let f = min(max((target - acc[j]) / seg, 0), 1)
            out.append(dense[j] + (dense[j + 1] - dense[j]) * f)
        }
        return out
    }

    /// Taper a sheet's end to a point: over its last `fraction` of length
    /// the two edges close on the midline smoothly (no facets, no corner
    /// where they happened to converge).
    static func taperEnd(_ a: inout [SIMD2<Float>], _ b: inout [SIMD2<Float>],
                         ts: [Float], fraction: Float) {
        let t0 = 1 - fraction
        for i in a.indices where ts[i] > t0 {
            let s = (ts[i] - t0) / fraction
            let w = smooth(s) * 0.6 + s * s * 0.4          // reaches 1 at the tip
            let mid = (a[i] + b[i]) / 2
            a[i] = a[i] + (mid - a[i]) * w
            b[i] = b[i] + (mid - b[i]) * w
        }
    }

}
