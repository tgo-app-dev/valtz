// The Valtz mark as geometry: its ribbon layers, traced from the painted
// original (the 1024 px artwork; y down), each a band between two edge
// curves.
//
// Why traced 2.5D layers and not a 3D ribbon: the artwork is a ribbon
// wrapped helically down a narrowing cone, folded at the base and
// doubled back behind the film strip -- several sheets whose visible
// edges ARE the design. Modelling that in 3D and hoping the projection
// lands on those edges did not get close; tracing the edges and
// shading each sheet as the surface it is does. Every layer is a
// triangle strip between its two edges (straight chords), drawn back to
// front, with colour baked per vertex from a small (t along, v across)
// table sampled from the artwork, and luminous rims and a metallic
// sheen added in the shader. The edges themselves are MEASURED from the
// artwork (MarkTrace.swift, generated by tools/valtz-icon/trace-mark).

import Metal
